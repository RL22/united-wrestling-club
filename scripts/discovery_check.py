#!/usr/bin/env python3
"""Maintain the discovery/ research library.

Commands:
  check              Validate the library schema and every relative markdown link under discovery/.
                     Prints each error and warning with its path, then a count per severity.
                     Exit 1 only when there are errors (warnings never change the exit code).
  index              Write a generated README.md index into every folder that directly holds library
                     docs. A README.md without the generated marker is hand-written and is skipped.
  manifest           Write discovery/manifest.json (path, title, status, group, type, owner, date,
                     last_reviewed, sources count, replaced_by) for agents. Writes nothing else.
  init-frontmatter   Legacy helper. Adds frontmatter to docs that have none, mapping old statuses
                     (current, reference, asset, partly-superseded, superseded, snapshot) to the new
                     ones. Dry run by default; pass --apply to write.

Environment:
  DISCOVERY_DIR      Discovery root to operate on (default <repo>/discovery). Point it at a fixture
                     to test.
  DISCOVERY_TODAY    Reference date for the stale-review warning (default 2026-11-06).

Library docs are .md files under discovery/{client,site,strategy,market,brand,archive}. README.md
files there are index pages: they skip frontmatter checks but their links are still checked.
Every library doc carries frontmatter:

    ---
    type: call | dossier | decision | spec | audit | inventory
    status: draft | current | superseded | archived
    group: client | site | strategy | market | brand | archive    (must equal the top folder)
    owner: <name>
    date: YYYY-MM-DD                  (the doc's own date)
    last_reviewed: YYYY-MM-DD
    sources: [list]                   (block list or inline [a, b])
    replaced_by: <discovery-relative path>   (required when status is superseded)
    caveat: <optional>
    title: <optional>
    ---

Errors: missing frontmatter; type, status or group outside its enum; group not the top folder;
superseded without replaced_by, or replaced_by missing on disk; call-type filename that does not
match YYYY-MM-DD_<client>_<topic>.md; broken relative markdown link (http, mailto, pure anchors and
absolute paths are skipped; fenced code blocks and scratch/ and video_assets/ are not scanned).

Warnings: sources empty or missing on dossier, spec or audit when status is draft or current;
last_reviewed more than 30 days before DISCOVERY_TODAY; no "## TL;DR" heading on status-current docs
in client, site or strategy; a folder with library docs whose README.md is missing or hand-written.
"""
import datetime
import json
import os
import re
import sys
import urllib.parse

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
DISC = os.path.abspath(os.environ.get('DISCOVERY_DIR') or os.path.join(REPO, 'discovery'))
GROUPS = ['client', 'site', 'strategy', 'market', 'brand', 'archive']
TYPES = ['call', 'dossier', 'decision', 'spec', 'audit', 'inventory']
STATUSES = ['draft', 'current', 'superseded', 'archived']
SOURCE_TYPES = {'dossier', 'spec', 'audit'}
SOURCE_STATUSES = {'draft', 'current'}
TLDR_GROUPS = {'client', 'site', 'strategy'}
STALE_DAYS = 30
DEFAULT_TODAY = '2026-11-06'
SKIP_DIRS = {'scratch', 'video_assets', 'node_modules', '.git'}
MARKER = '<!-- generated by scripts/discovery_check.py index; do not edit -->'
CAVEAT_PARTLY = ('Partly superseded: findings still apply, some recommendations were replaced. '
                 'See the banner in this doc.')
# legacy status -> (new status, caveat)
LEGACY_STATUS = {
    'current': ('current', None),
    'reference': ('current', None),
    'asset': ('current', None),
    'partly-superseded': ('current', CAVEAT_PARTLY),
    'superseded': ('superseded', None),
    'snapshot': ('archived', None),
}
LEGACY_DEFAULT = {'archive/superseded': 'superseded', 'archive/snapshots': 'snapshot',
                  'market': 'reference', 'brand': 'reference'}
CALL_NAME = re.compile(r'^\d{4}-\d{2}-\d{2}_[a-z0-9-]+_[a-z0-9-]+\.md$')
DATE = re.compile(r'^\d{4}-\d{2}-\d{2}$')
FM = re.compile(r'\A---[ \t]*\n((?:.*?\n)?)---[ \t]*(?:\n|\Z)', re.S)
LINK = re.compile(r'\]\(([^)\s]+)\)')
FENCE = re.compile(r'^\s*(```|~~~)')
SCHEME = re.compile(r'^[A-Za-z][A-Za-z0-9+.-]*:')
TLDR = re.compile(r'^## TL;DR[ \t]*$', re.M)
H1 = re.compile(r'^# (.+)$', re.M)


# ---------- helpers ----------

def show(p):
    """Repo-relative path when inside the repo, else absolute (fixtures)."""
    if p == REPO or p.startswith(REPO + os.sep):
        return os.path.relpath(p, REPO)
    return p


def rel_of(p):
    return os.path.relpath(p, DISC).replace(os.sep, '/')


def read(p):
    with open(p, encoding='utf-8') as f:
        return f.read()


def first_line(text):
    return text.split('\n', 1)[0].strip()


def md_files():
    """Every .md under DISC except SKIP_DIRS, sorted. Yields (abs_path, discovery-relative posix path)."""
    for dp, dn, fn in os.walk(DISC):
        dn[:] = sorted(d for d in dn if d not in SKIP_DIRS)
        for f in sorted(fn):
            if f.endswith('.md'):
                p = os.path.join(dp, f)
                yield p, rel_of(p)


def library_docs(include_readme=False):
    for p, rel in md_files():
        if rel.split('/')[0] not in GROUPS:
            continue
        if os.path.basename(p) == 'README.md' and not include_readme:
            continue
        yield p, rel


def unquote(s):
    if len(s) >= 2 and s[0] == s[-1] and s[0] in '"\'':
        return s[1:-1]
    return s


def parse_fm(text):
    """Return frontmatter as a dict (scalars are str, lists are list), or None if there is no block."""
    m = FM.match(text)
    if not m:
        return None
    out, key = {}, None
    for raw in m.group(1).splitlines():
        if not raw.strip() or raw.lstrip().startswith('#'):
            continue
        if raw[0] in ' \t':  # indented: block-list item under the current key
            if key is not None and isinstance(out.get(key), list) and raw.strip().startswith('- '):
                out[key].append(unquote(raw.strip()[2:].strip()))
            continue
        if ':' not in raw:
            key = None
            continue
        k, v = raw.split(':', 1)
        key, v = k.strip(), v.strip()
        if not v:
            out[key] = []
        elif v.startswith('['):
            out[key] = [unquote(x.strip()) for x in v.strip('[]').split(',') if x.strip()]
        else:
            out[key] = unquote(v)
    return out


def scalar(fm, key):
    v = fm.get(key) if fm else None
    return v if isinstance(v, str) and v else None


def items(fm, key):
    v = fm.get(key) if fm else None
    if isinstance(v, list):
        return [x for x in v if x]
    return [v] if isinstance(v, str) and v else []


def body_of(text):
    m = FM.match(text)
    return text[m.end():] if m else text


def first_h1(body):
    m = H1.search(body)
    return m.group(1).strip() if m else None


def parse_date(s):
    if not s or not DATE.match(s):
        return None
    try:
        return datetime.date.fromisoformat(s)
    except ValueError:
        return None


def shown_or_missing(v):
    return repr(v) if v else 'missing'


# ---------- check ----------

def check_links(errors):
    for p, _ in md_files():
        in_fence = False
        for n, line in enumerate(read(p).splitlines(), 1):
            if FENCE.match(line):
                in_fence = not in_fence
                continue
            if in_fence:
                continue
            for m in LINK.finditer(line):
                t = m.group(1)
                if t.startswith(('#', '/')) or SCHEME.match(t):
                    continue
                path = urllib.parse.unquote(t.split('#', 1)[0])
                if not path:
                    continue
                target = os.path.normpath(os.path.join(os.path.dirname(p), path))
                if not os.path.exists(target):
                    errors.append((f"{show(p)}:{n}", f"broken link -> {t}"))


def check_docs(errors, warnings, today):
    for p, rel in library_docs():
        shown = show(p)
        text = read(p)
        fm = parse_fm(text)
        if fm is None:
            errors.append((shown, 'no frontmatter'))
            continue
        top = rel.split('/')[0]
        typ, status, group = scalar(fm, 'type'), scalar(fm, 'status'), scalar(fm, 'group')

        if typ not in TYPES:
            errors.append((shown, f"type {shown_or_missing(typ)} is not one of {' | '.join(TYPES)}"))
        if status not in STATUSES:
            errors.append((shown, f"status {shown_or_missing(status)} is not one of {' | '.join(STATUSES)}"))
        if group not in GROUPS:
            errors.append((shown, f"group {shown_or_missing(group)} is not one of {' | '.join(GROUPS)}"))
        elif group != top:
            errors.append((shown, f"group {group!r} does not match folder {top!r}"))

        if status == 'superseded':
            rb = scalar(fm, 'replaced_by')
            if rb is None:
                errors.append((shown, 'status superseded requires replaced_by'))
            elif not os.path.isfile(os.path.join(DISC, rb)):
                errors.append((shown, f"replaced_by {rb!r} does not exist (relative to discovery/)"))

        if typ == 'call' and not CALL_NAME.match(os.path.basename(p)):
            errors.append((shown, 'call doc filename must match YYYY-MM-DD_<client>_<topic>.md'))

        if typ in SOURCE_TYPES and status in SOURCE_STATUSES and not items(fm, 'sources'):
            warnings.append((shown, f"sources empty or missing on {typ} doc (status {status})"))

        reviewed = parse_date(scalar(fm, 'last_reviewed'))
        if reviewed is not None:
            age = (today - reviewed).days
            if age > STALE_DAYS:
                warnings.append((shown, f"last_reviewed {reviewed} is {age} days before today (limit {STALE_DAYS})"))

        if status == 'current' and top in TLDR_GROUPS and not TLDR.search(body_of(text)):
            warnings.append((shown, "status current but no '## TL;DR' heading"))


def check_readmes(warnings):
    folders = sorted({os.path.dirname(p) for p, _ in library_docs()})
    for d in folders:
        readme = os.path.join(d, 'README.md')
        if not os.path.isfile(readme):
            warnings.append((show(readme), 'folder holds library docs but has no generated README.md (run index)'))
        elif first_line(read(readme)) != MARKER:
            warnings.append((show(readme), 'README.md is hand-written (no generated marker); index will not overwrite it'))


def run_check():
    try:
        today = parse_date(os.environ.get('DISCOVERY_TODAY', DEFAULT_TODAY))
    except ValueError:
        today = None
    if today is None:
        print("DISCOVERY_TODAY must be YYYY-MM-DD", file=sys.stderr)
        return 2
    errors, warnings = [], []
    check_links(errors)
    check_docs(errors, warnings, today)
    check_readmes(warnings)
    for path, msg in errors:
        print(f"ERROR  {path}: {msg}")
    for path, msg in warnings:
        print(f"WARN   {path}: {msg}")
    print(f"{len(errors)} error(s)")
    print(f"{len(warnings)} warning(s)")
    return 1 if errors else 0


# ---------- index ----------

def cell(v):
    return '-' if not v else str(v).replace('|', '\\|')


def build_index():
    folders = {}
    for p, _ in library_docs():
        folders.setdefault(os.path.dirname(p), []).append(p)
    for d in sorted(folders):
        readme = os.path.join(d, 'README.md')
        if os.path.isfile(readme) and first_line(read(readme)) != MARKER:
            print(f"skipped (hand-written): {show(readme)}")
            continue
        rows = []
        for p in sorted(folders[d], key=os.path.basename):
            text = read(p)
            fm = parse_fm(text) or {}
            name = os.path.basename(p)
            title = scalar(fm, 'title') or first_h1(body_of(text)) or name
            rows.append(
                f"| [`{name}`]({urllib.parse.quote(name)}) | {cell(scalar(fm, 'type'))} | "
                f"{cell(scalar(fm, 'status'))} | {cell(scalar(fm, 'last_reviewed'))} | {cell(title)} |")
        lines = [MARKER, f"# {os.path.basename(d)}", '',
                 '| Doc | Type | Status | Last reviewed | Title |', '|---|---|---|---|---|', *rows]
        with open(readme, 'w', encoding='utf-8') as f:
            f.write('\n'.join(lines) + '\n')
        print(f"wrote {show(readme)} ({len(rows)} docs)")
    return 0


# ---------- manifest ----------

def build_manifest():
    entries = []
    for p, rel in library_docs(include_readme=True):
        text = read(p)
        fm = parse_fm(text) or {}
        entries.append({
            'path': rel,
            'title': scalar(fm, 'title') or first_h1(body_of(text)) or os.path.basename(p),
            'status': scalar(fm, 'status'),
            'group': scalar(fm, 'group'),
            'type': scalar(fm, 'type'),
            'owner': scalar(fm, 'owner'),
            'date': scalar(fm, 'date'),
            'last_reviewed': scalar(fm, 'last_reviewed'),
            'sources': len(items(fm, 'sources')),
            'replaced_by': scalar(fm, 'replaced_by'),
        })
    entries.sort(key=lambda e: (e['group'] or '', e['path']))
    out = os.path.join(DISC, 'manifest.json')
    with open(out, 'w', encoding='utf-8') as f:
        json.dump({'generated_by': 'scripts/discovery_check.py manifest', 'docs': entries}, f, indent=2)
        f.write('\n')
    print(f"wrote {show(out)} ({len(entries)} docs)")
    return 0


# ---------- init-frontmatter (legacy) ----------

def readme_statuses():
    """Map discovery-relative doc path -> legacy status, from the index tables in discovery/README.md."""
    path = os.path.join(DISC, 'README.md')
    if not os.path.isfile(path):
        return {}
    out = {}
    row = re.compile(r'^\|\s*\[`[^`]+`\]\(([^)\s]+)\)\s*\|\s*([^|]+?)\s*\|', re.M)
    for m in row.finditer(read(path)):
        target = urllib.parse.unquote(m.group(1).split('#')[0])
        status = normalize_status(m.group(2))
        if status and target.endswith('.md'):
            out[os.path.normpath(target).replace(os.sep, '/')] = status
    return out


def normalize_status(text):
    t = re.sub(r'\(.*?\)', '', text).strip().lower()
    if t.startswith('partly superseded'):
        return 'partly-superseded'
    for s in ('current', 'reference', 'snapshot', 'superseded', 'asset'):
        if t.startswith(s):
            return s
    return None


def legacy_default(rel):
    for prefix, status in LEGACY_DEFAULT.items():
        if rel.startswith(prefix + '/'):
            return status
    return None


def init_frontmatter(apply):
    known = readme_statuses()
    plan, unclassified = [], []
    for p, rel in library_docs():
        text = read(p)
        if parse_fm(text) is not None:
            continue
        old = known.get(rel) or legacy_default(rel)
        if old not in LEGACY_STATUS:
            unclassified.append(rel)
            continue
        status, caveat = LEGACY_STATUS[old]
        block = ['---', f'status: {status}', f'group: {rel.split("/")[0]}']
        if caveat:
            block.append(f'caveat: "{caveat}"')
        block.append('---')
        plan.append((p, rel, old, status, '\n'.join(block) + '\n\n' + text))
    for p, rel, old, status, new in plan:
        print(f"{old:20s} -> {status:12s} {rel}")
        if apply:
            with open(p, 'w', encoding='utf-8') as f:
                f.write(new)
    superseded = sum(1 for plan_item in plan if plan_item[3] == 'superseded')
    print(f"\n{len(plan)} docs {'updated' if apply else 'to update (dry run)'}; unclassified: {len(unclassified)}")
    for u in unclassified:
        print('  unclassified:', u)
    if superseded:
        print(f"  {superseded} superseded doc(s) need replaced_by and type before check passes")
    return 0


# ---------- entry ----------

def main(argv):
    cmd = argv[1] if len(argv) > 1 else 'check'
    if cmd not in ('check', 'index', 'manifest', 'init-frontmatter'):
        print(__doc__)
        return 2
    if not os.path.isdir(DISC):
        print(f"discovery root not found: {DISC}", file=sys.stderr)
        return 2
    if cmd == 'check':
        return run_check()
    if cmd == 'index':
        return build_index()
    if cmd == 'manifest':
        return build_manifest()
    return init_frontmatter('--apply' in argv[2:])


if __name__ == '__main__':
    sys.exit(main(sys.argv))
